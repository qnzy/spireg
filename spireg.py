#!/usr/bin/env python3
"""
SPI Register Interface Generator
Generates Verilog-2005 compatible SPI slave + register file from CSV specification
The SPI and the registers are directly clocked with SCLK, no other clock is required.

SPI protocol:
- Byte 0: RW bit (1) + 7-bit address
- Byte 1+: 8-bit data (write data or dummy for read)
- rw: 1 for write, 0 for read
- Multi-byte transfers: address auto-increments after each data byte
- Address saturates at 0x7F (does NOT wrap to 0x00)
- Maximum transfer: 128 bytes (1 command + 127 data bytes)
- Mode 0: CPOL=0, CPHA=0

CSV format:
- First line must contain (in any order): reg_name,field_name,lsb,msb,type,reset
- Following lines define register fields.
- reg_name can be empty to reuse from previous line.
- type can be rw (read/write) or ro (read only)
- rw creates output from the regmap, ro generate input to the regmap
"""

import csv
import sys
from pathlib import Path


def parse_csv(csv_file):
    """Parse CSV file and return register definitions"""
    registers = []

    with open(csv_file, "r") as f:
        reader = csv.DictReader(f)

        # Validate required columns
        required_cols = {"reg_name", "field_name", "lsb", "msb", "type", "reset"}
        if not required_cols.issubset(set(reader.fieldnames or [])):
            raise ValueError(f"CSV must contain columns: {required_cols}")

        current_reg = None
        last_reg_name = None

        for row in reader:
            # Handle missing reg_name (reuse from previous line)
            reg_name = (row.get("reg_name") or "").strip()
            if not reg_name:
                if last_reg_name is None:
                    raise ValueError("First row must have a reg_name")
                reg_name = last_reg_name
            else:
                last_reg_name = reg_name

            field_name = (row.get("field_name") or "").strip()
            lsb = int(row["lsb"])
            msb = int(row["msb"])
            field_type = (row.get("type") or "").strip().lower()
            reset_val = (row.get("reset") or "").strip()

            # Validate field type
            if field_type not in ["rw", "ro"]:
                raise ValueError(
                    f"Invalid type '{field_type}' for {reg_name}.{field_name}. Must be 'rw' or 'ro'"
                )

            # Validate bit range
            if lsb > msb or msb > 7 or lsb < 0:
                raise ValueError(f"Invalid bit range [{msb}:{lsb}] for {reg_name}.{field_name}")

            # Start new register or add field to current
            if current_reg is None or current_reg["name"] != reg_name:
                if current_reg is not None:
                    registers.append(current_reg)
                current_reg = {"name": reg_name, "fields": []}

            current_reg["fields"].append(
                {
                    "name": field_name,
                    "lsb": lsb,
                    "msb": msb,
                    "width": msb - lsb + 1,
                    "type": field_type,
                    "reset": reset_val,
                }
            )

        if current_reg is not None:
            registers.append(current_reg)

    # Check for field overlaps within each register
    for reg in registers:
        bits_used = [False] * 8
        for field in reg["fields"]:
            for bit in range(field["lsb"], field["msb"] + 1):
                if bits_used[bit]:
                    raise ValueError(
                        f"Bit {bit} in register '{reg['name']}' is used by multiple fields"
                    )
                bits_used[bit] = True

    return registers


def _parse_reset_to_int(reset_str: str) -> int:
    s = reset_str.strip()
    if not s:
        return 0
    if s.startswith(("0x", "0X")):
        return int(s, 16)
    if s.startswith(("0b", "0B")):
        return int(s, 2)
    return int(s, 10)


def generate_verilog(registers, output_file):
    """
    Generate complete SPI register interface with the following features:
    - 10-bit bit_count: supports up to 128-byte transfers
    - Address saturation: stops at 0x7F (no wrap to 0x00)
    - Single procedural driver: addr/byte_count owned by receive block only
    - Mode 0 (CPOL=0, CPHA=0)
    - Mixed RO/RW register support with bit-level masking
    """

    addr_width = 7
    data_width = 8
    bit_count_width = 10  # 10 bits: 0-1023, supports 128 bytes (1 cmd + 127 data)
    max_addr = 127  # Maximum valid 7-bit address (0x7F)
    num_regs = len(registers)

    # Assign sequential addresses
    for idx, reg in enumerate(registers):
        reg["addr"] = idx

    v = []  # Verilog lines

    # Header
    v.append("// Auto-generated Complete SPI Register Interface")
    v.append("// Generated by spireg.py from CSV specification")
    v.append("// Verilog-2005 compatible")
    v.append("// Protocol: Variable-length transfers")
    v.append("//   Byte 0: 1 RW bit + 7-bit address")
    v.append("//   Byte 1+: 8-bit data (auto-increment address after each byte)")
    v.append("//   Address saturates at 0x7F (no wrap), supports up to 128-byte transfers")
    v.append("// Mode 0: CPOL=0, CPHA=0")
    v.append("// Note: core drives MISO always; pad-ring may tri-state when cs_n=1")
    v.append("")
    v.append("`timescale 1ns / 1ps")
    v.append("")

    # Collect all RO and RW fields
    ro_fields = []
    rw_fields = []
    for reg in registers:
        for field in reg["fields"]:
            field["reg_name"] = reg["name"]
            field["reg_addr"] = reg["addr"]
            if field["type"] == "ro":
                ro_fields.append(field)
            else:
                rw_fields.append(field)

    # Module declaration (build port list first to avoid trailing comma bugs)
    port_items = []  # each item: ("port"|"comment"|"blank", text)
    port_items.append(("comment", "    // SPI interface"))
    port_items.append(("port",    "    input  wire       sclk"))
    port_items.append(("port",    "    input  wire       mosi"))
    port_items.append(("port",    "    output reg        miso"))
    port_items.append(("port",    "    input  wire       cs_n"))
    port_items.append(("blank",   "    "))
    port_items.append(("comment", "    // System reset"))
    port_items.append(("port",    "    input  wire       rst_n"))

    if ro_fields:
        port_items.append(("blank",   "    "))
        port_items.append(("comment", "    // Read-only field inputs"))
        for field in ro_fields:
            signal_name = f"{field['reg_name']}_{field['name']}_i"
            if field["width"] == 1:
                port_items.append(("port", f"    input  wire       {signal_name}"))
            else:
                port_items.append(("port", f"    input  wire [{field['width']-1}:0] {signal_name}"))

    if rw_fields:
        port_items.append(("blank",   "    "))
        port_items.append(("comment", "    // Read-write field outputs"))
        for field in rw_fields:
            signal_name = f"{field['reg_name']}_{field['name']}_o"
            if field["width"] == 1:
                port_items.append(("port", f"    output wire       {signal_name}"))
            else:
                port_items.append(("port", f"    output wire [{field['width']-1}:0] {signal_name}"))

    v.append("module spi_reg_interface (")
    # Add commas to all port lines except the last one
    last_port_idx = max(i for i, (k, _) in enumerate(port_items) if k == "port")
    for i, (kind, line) in enumerate(port_items):
        if kind == "port":
            v.append(line + ("," if i != last_port_idx else ""))
        else:
            v.append(line)
    v.append(");")
    v.append("")
    v.append("")

    # Register declarations
    v.append("    //========================================================================")
    v.append("    // Register Declarations")
    v.append("    //========================================================================")
    v.append("    ")
    v.append("    // SPI receive/transmit state (Mode 0)")
    v.append("    reg [15:0] rx_shift;")
    v.append(f"    reg [{bit_count_width-1}:0]  bit_count;  // {bit_count_width} bits: supports 128-byte transfers")
    v.append("    reg        rw_bit;")
    v.append("    reg [6:0]  addr;")
    v.append("    reg [7:0]  byte_count;  // Track number of data bytes transferred")
    v.append("    ")
    v.append("    reg [7:0]  tx_shift;")
    v.append("    reg        tx_active;")
    v.append("    reg [7:0]  read_byte;")
    v.append("    ")
    v.append("    wire [15:0] rx_next = {rx_shift[14:0], mosi};")
    v.append("    ")

    v.append("    // Register file storage (only for registers with RW fields)")
    for reg in registers:
        has_rw = any(f["type"] == "rw" for f in reg["fields"])
        if has_rw:
            v.append(f"    reg [7:0] {reg['name']}_reg;")
    v.append("")

    # Add 2-FF synchronizers for all RO inputs (CDC protection)
    if ro_fields:
        v.append("    //========================================================================")
        v.append("    // 2-FF Synchronizers for RO inputs (CDC protection)")
        v.append("    // Prevents metastability from async inputs propagating to MISO output")
        v.append("    //========================================================================")
        v.append("    ")
        
        # Declare sync registers
        for field in ro_fields:
            signal_name = f"{field['reg_name']}_{field['name']}"
            if field["width"] == 1:
                v.append(f"    reg {signal_name}_sync1, {signal_name}_sync2;")
            else:
                v.append(f"    reg [{field['width']-1}:0] {signal_name}_sync1, {signal_name}_sync2;")
        
        v.append("")
        v.append("    // Synchronizer logic: input → sync1 → sync2")
        v.append("    always @(posedge sclk or negedge rst_n) begin")
        v.append("        if (!rst_n) begin")
        
        # Reset sync registers
        for field in ro_fields:
            signal_name = f"{field['reg_name']}_{field['name']}"
            if field["width"] == 1:
                v.append(f"            {signal_name}_sync1 <= 1'b0;")
                v.append(f"            {signal_name}_sync2 <= 1'b0;")
            else:
                v.append(f"            {signal_name}_sync1 <= {field['width']}'d0;")
                v.append(f"            {signal_name}_sync2 <= {field['width']}'d0;")
        
        v.append("        end")
        v.append("        else begin")
        v.append("            // First stage")
        for field in ro_fields:
            signal_name = f"{field['reg_name']}_{field['name']}"
            v.append(f"            {signal_name}_sync1 <= {signal_name}_i;")
        
        v.append("            // Second stage (output)")
        for field in ro_fields:
            signal_name = f"{field['reg_name']}_{field['name']}"
            v.append(f"            {signal_name}_sync2 <= {signal_name}_sync1;")
        
        v.append("        end")
        v.append("    end")
        v.append("")


    # Combinational read mux (read_byte) - FIXED FOR MIXED FIELDS
    v.append("    //========================================================================")
    v.append("    // Read mux (combinational) -> read_byte")
    v.append("    //========================================================================")
    v.append("    ")
    v.append("    always @* begin")
    v.append("        read_byte = 8'h00;  // Default")
    v.append("        case (addr)")

    for reg in registers:
        v.append(f"            7'h{reg['addr']:02x}: begin")
        
        # Build bit-by-bit sources, considering both RW and RO fields
        bit_sources = ["1'b0"] * 8
        
        for field in reg["fields"]:
            if field["type"] == "rw":
                # RW field comes from stored register
                for bit in range(field["lsb"], field["msb"] + 1):
                    bit_sources[7 - bit] = f"{reg['name']}_reg[{bit}]"
            else:
                # RO field comes from synchronized input (CDC-safe)
                sig = f"{reg['name']}_{field['name']}_sync2"
                for bit in range(field["lsb"], field["msb"] + 1):
                    if field["width"] == 1:
                        bit_sources[7 - bit] = sig
                    else:
                        bit_sources[7 - bit] = f"{sig}[{bit - field['lsb']}]"
        
        v.append("                read_byte = {")
        v.append("                    " + ", ".join(bit_sources))
        v.append("                };")
        v.append("            end")

    v.append("            default: begin")
    v.append("                read_byte = 8'h00;")
    v.append("            end")
    v.append("        endcase")
    v.append("    end")
    v.append("")

    # SPI Receive block (posedge sclk) - owns addr and byte_count
    v.append("    //========================================================================")
    v.append("    // SPI Receive (Mode 0): sample MOSI on SCLK rising edge")
    v.append("    // This block owns addr and byte_count (single procedural driver)")
    v.append("    //========================================================================")
    v.append("    ")
    v.append("    always @(posedge sclk or posedge cs_n or negedge rst_n) begin")
    v.append("        if (!rst_n) begin")
    v.append("            rx_shift  <= 16'd0;")
    v.append(f"            bit_count <= {bit_count_width}'d0;")
    v.append("            rw_bit    <= 1'b0;")
    v.append("            addr      <= 7'd0;")
    v.append("            byte_count <= 8'd0;")
    v.append("        end")
    v.append("        else if (cs_n) begin")
    v.append("            // Not selected: reset framing state")
    v.append("            rx_shift  <= 16'd0;")
    v.append(f"            bit_count <= {bit_count_width}'d0;")
    v.append("            rw_bit    <= 1'b0;")
    v.append("            addr      <= 7'd0;")
    v.append("            byte_count <= 8'd0;")
    v.append("        end")
    v.append("        else begin")
    v.append("            // Shift in MOSI")
    v.append("")
    v.append("            // Capture RW bit on first clock")
    v.append(f"            if (bit_count == {bit_count_width}'d0) begin")
    v.append("                rw_bit <= mosi;")
    v.append("            end")
    v.append("")
    v.append("            // Capture address after 8 clocks (byte0 bits[6:0])")
    v.append(f"            if (bit_count == {bit_count_width}'d7) begin")
    v.append("                addr <= rx_next[6:0];")
    v.append("                byte_count <= 8'd0;  // Reset byte counter at start")
    v.append("            end")
    v.append("")
    v.append("            // Auto-increment address at byte boundaries for BOTH reads AND writes")
    v.append("            // Triggers at bit_count==15, 23, 31, ..., 1015, 1023 (when lower 3 bits == 7)")
    v.append("            // Special case: bit_count==1023 triggers ONCE, then stops")
    v.append("            // Address saturates at max (no wrap)")
    v.append(f"            if (bit_count >= {bit_count_width}'d15 && ((bit_count[2:0]) == 3'd7)) begin")
    v.append(f"                if (bit_count < {bit_count_width}'d1023) begin")
    v.append(f"                    // Normal byte boundary (15, 23, 31, ..., 1015)")
    v.append(f"                    if (addr < 7'd{max_addr})")
    v.append(f"                        addr <= addr + 7'd1;")
    v.append("                    byte_count <= byte_count + 8'd1;")
    v.append("                end")
    v.append(f"                else if (bit_count == {bit_count_width}'d1023 && byte_count < 8'd127) begin")
    v.append(f"                    // Final byte boundary (bit_count==1023), only trigger if not already done")
    v.append(f"                    // byte_count < 127 ensures this only happens once")
    v.append("                    byte_count <= 8'd127;  // Mark as complete")
    v.append("                    // addr already at 0x7F, no increment needed")
    v.append("                end")
    v.append("            end")
    v.append("")
    v.append("            // Always shift and increment bit counter")
    v.append("            rx_shift <= rx_next;")
    v.append(f"            // Saturate bit_count at max to prevent wraparound after 128 bytes")
    v.append(f"            if (bit_count < {bit_count_width}'d{(1 << bit_count_width) - 1})")
    v.append(f"                bit_count <= bit_count + {bit_count_width}'d1;")
    v.append("        end")
    v.append("    end")
    v.append("")

    # Register file write logic (posedge sclk, commit at bit 15)
    v.append("    //========================================================================")
    v.append("    // Register File Write Logic (commit on 16th SCLK rising edge)")
    v.append("    //========================================================================")
    v.append("    ")
    v.append("    always @(posedge sclk or posedge cs_n or negedge rst_n) begin")
    v.append("        if (!rst_n) begin")
    for reg in registers:
        has_rw = any(f["type"] == "rw" for f in reg["fields"])
        if has_rw:
            reset_val = 0
            for field in reg["fields"]:
                if field["type"] == "rw":
                    fval = _parse_reset_to_int(field["reset"])
                    width = field["msb"] - field["lsb"] + 1
                    mask = (1 << width) - 1
                    reset_val |= (fval & mask) << field["lsb"]
            v.append(f"            {reg['name']}_reg <= 8'h{reset_val:02x};")
    v.append("        end")
    v.append("        else if (cs_n) begin")
    v.append("            // CS deasserted - no action needed, registers hold state")
    v.append("        end")
    v.append("        else begin")
    v.append("            // Write commits at every byte boundary: bit_count==15, 23, 31, ...")
    v.append("            // For multi-byte writes: each complete data byte triggers a write")
    v.append("            // Check: bit_count>=15 AND (bit_count-15) is a multiple of 8")
    v.append("            // CRITICAL: Stop at bit_count==1022 to prevent continuous triggering at 1023")
    v.append(f"            if (rw_bit && bit_count >= {bit_count_width}'d15 && bit_count < {bit_count_width}'d1023 && ((bit_count[2:0]) == 3'd7)) begin")
    v.append("                // On byte boundary, rx_next[7:0] contains the complete data byte")
    v.append("                case (addr)")
    for reg in registers:
        has_rw = any(f["type"] == "rw" for f in reg["fields"])
        if has_rw:
            # Generate write with RO field masking if needed
            has_ro = any(f["type"] == "ro" for f in reg["fields"])
            if has_ro:
                # Build bit-wise assignment
                v.append(f"                    7'h{reg['addr']:02x}: begin")
                v.append(f"                        // Mixed RO/RW register - only write to RW bits")
                
                for bit in range(8):
                    # Check if this bit belongs to an RW field
                    is_rw_bit = False
                    for field in reg["fields"]:
                        if field["type"] == "rw" and field["lsb"] <= bit <= field["msb"]:
                            is_rw_bit = True
                            break
                    
                    if is_rw_bit:
                        v.append(f"                        {reg['name']}_reg[{bit}] <= rx_next[{bit}];")
                
                v.append("                    end")
            else:
                # Pure RW register - write entire byte
                v.append(f"                    7'h{reg['addr']:02x}: {reg['name']}_reg <= rx_next[7:0];")
    v.append("                    default: ;")
    v.append("                endcase")
    v.append("                // Note: addr and byte_count increment handled in receive block")
    v.append("            end")
    v.append("        end")
    v.append("    end")
    v.append("")

    # SPI Transmit block (negedge sclk)
    v.append("    //========================================================================")
    v.append("    // SPI Transmit (Mode 0): update MISO on SCLK falling edge")
    v.append("    //========================================================================")
    v.append("    ")
    v.append("    always @(negedge sclk or posedge cs_n or negedge rst_n) begin")
    v.append("        if (!rst_n) begin")
    v.append("            miso      <= 1'b0;")
    v.append("            tx_shift  <= 8'd0;")
    v.append("            tx_active <= 1'b0;")
    v.append("        end")
    v.append("        else if (cs_n) begin")
    v.append("            // Not selected: stop TX state (pad can tri-state externally)")
    v.append("            miso      <= 1'b0;")
    v.append("            tx_shift  <= 8'd0;")
    v.append("            tx_active <= 1'b0;")
    v.append("        end")
    v.append("        else begin")
    v.append("            // After address phase: for READ, start shifting out read data")
    v.append("            // At 8th falling edge (bit_count==8), addr is stable, read_byte is valid")
    v.append("            // For multi-byte reads, reload tx_shift at bit_count==16, 24, 32, ...")
    v.append(f"            if (!rw_bit && (bit_count == {bit_count_width}'d8)) begin")
    v.append("                // First data byte")
    v.append("                miso      <= read_byte[7];")
    v.append("                tx_shift  <= {read_byte[6:0], 1'b0};")
    v.append("                tx_active <= 1'b1;")
    v.append("            end")
    v.append(f"            else if (!rw_bit && tx_active && bit_count >= {bit_count_width}'d16 && bit_count <= {bit_count_width}'d1023 && ((bit_count[2:0]) == 3'd0)) begin")
    v.append("                // Reload for next byte at bit_count==16, 24, 32, ...")
    v.append("                // Address was already incremented by receive block")
    v.append("                // Stop reloading after 128 bytes")
    v.append("                miso      <= read_byte[7];")
    v.append("                tx_shift  <= {read_byte[6:0], 1'b0};")
    v.append("            end")
    v.append("            else if (tx_active) begin")
    v.append("                // Shift out current byte")
    v.append("                miso     <= tx_shift[7];")
    v.append("                tx_shift <= {tx_shift[6:0], 1'b0};")
    v.append("            end")
    v.append("            else begin")
    v.append("                // During command/address phase (or writes), drive 0")
    v.append("                miso <= 1'b0;")
    v.append("            end")
    v.append("        end")
    v.append("    end")
    v.append("")

    # Output assignments - map register bits to field outputs
    v.append("    //========================================================================")
    v.append("    // Output Assignments")
    v.append("    //========================================================================")
    v.append("    ")

    for field in rw_fields:
        reg_name = field["reg_name"]
        sig = f"{reg_name}_{field['name']}_o"
        if field["width"] == 1:
            v.append(f"    assign {sig} = {reg_name}_reg[{field['lsb']}];")
        else:
            v.append(f"    assign {sig} = {reg_name}_reg[{field['msb']}:{field['lsb']}];")

    v.append("")
    v.append("endmodule")

    # Write to file
    with open(output_file, "w") as f:
        f.write("\n".join(v))

    print(f"Generated complete SPI register interface: {output_file}")
    print(f"  Registers: {num_regs}")
    print(f"  Total fields: {len(ro_fields) + len(rw_fields)}")
    print(f"    RW fields: {len(rw_fields)}")
    print(f"    RO fields: {len(ro_fields)}")
    print(f"  Address width: {addr_width} bits (0x00-0x{max_addr:02X})")
    print(f"  Data width: {data_width} bits")
    print(f"  bit_count width: {bit_count_width} bits (max {2**bit_count_width} bits = {2**bit_count_width // 8} bytes)")
    print(f"  Address behavior: Saturates at 0x{max_addr:02X} (no wrap)")
    print(f"  Max transfer: {max_addr + 1} bytes per transaction")


def main():
    if len(sys.argv) != 3:
        print("Usage: spireg.py <input.csv> <output.v>")
        sys.exit(1)

    csv_file = sys.argv[1]
    output_file = sys.argv[2]

    if not Path(csv_file).exists():
        print(f"Error: Input file '{csv_file}' not found")
        sys.exit(1)

    try:
        registers = parse_csv(csv_file)
        generate_verilog(registers, output_file)
    except Exception as e:
        print(f"Error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
